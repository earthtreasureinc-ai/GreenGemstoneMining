"""Builds src/data/mapData.ts: Somaliland outline, regions and generalised geology belts as SVG paths.

Inputs (not committed; download them first):
  ne_10m_admin_0_countries.geojson  (Natural Earth, public domain)  -> national outline
  som1.geojson                      (geoBoundaries SOM ADM1, CC BY 4.0) -> region shapes
Usage: python3 scripts/build-map-data.py <ne_countries.geojson> <geoboundaries_som_adm1.geojson> > src/data/mapData.ts
Region borders are approximate: Sahil is cut from Woqooyi Galbeed at ~9.95N, and slivers between the two
sources are assigned to the neighbouring region. Geology belts are hand-drawn generalisations.
"""
import json, math, sys
from shapely.geometry import shape, Polygon, Point, mapping
from shapely.ops import unary_union

ne = json.load(open(sys.argv[1]))
gb = json.load(open(sys.argv[2]))
outline = shape([f for f in ne['features'] if f['properties']['ADMIN'] == 'Somaliland'][0]['geometry']).buffer(0)

raw = {f['properties']['shapeName']: shape(f['geometry']).buffer(0) for f in gb['features']}
parts = {
    'Awdal': raw['Awdal'], 'Togdheer': raw['Togdheer'], 'Sanaag': raw['Sanaag'], 'Sool': raw['Sool'],
}
wg = raw['Woqooyi Galbeed']
cut = Polygon([(40, 9.95), (50, 9.95), (50, 13), (40, 13)])
parts['Sahil'] = wg.intersection(cut)
parts['Maroodi Jeex'] = wg.difference(cut)
parts = {k: v.intersection(outline) for k, v in parts.items()}

# Assign slivers of the outline not covered by any region to the neighbour they touch most.
left = outline.difference(unary_union(list(parts.values())))
geoms = list(left.geoms) if hasattr(left, 'geoms') else [left]
for g in geoms:
    if g.area < 1e-6:
        continue
    best = max(parts, key=lambda k: parts[k].buffer(0.03).intersection(g).area)
    parts[best] = unary_union([parts[best], g.buffer(0.0005)])
for k in parts:
    g = parts[k].buffer(0.002).buffer(-0.002)
    polys = [q for q in (g.geoms if hasattr(g, 'geoms') else [g]) if q.area > 0.03]  # drop stray slivers
    parts[k] = unary_union(polys)

minx, miny, maxx, maxy = outline.bounds
K = 150.0  # px per degree of latitude
cosl = math.cos(math.radians((miny + maxy) / 2))
pad = 18
W = (maxx - minx) * cosl * K + pad * 2
H = (maxy - miny) * K + pad * 2
def P(x, y): return ((x - minx) * cosl * K + pad, (maxy - y) * K + pad)

def path(geom, tol=0.004):
    g = geom.simplify(tol, preserve_topology=True)
    polys = list(g.geoms) if hasattr(g, 'geoms') else [g]
    out = []
    for p in polys:
        if p.is_empty or p.geom_type != 'Polygon': continue
        for ring in [p.exterior, *p.interiors]:
            pts = [P(*c) for c in ring.coords]
            out.append('M' + 'L'.join(f'{x:.1f} {y:.1f}' for x, y in pts[:-1]) + 'Z')
    return ''.join(out)

def rep(g):
    pt = g.representative_point()
    return P(pt.x, pt.y)

# Generalised geology belts (lon, lat), clipped to the outline.
escarp = [(42.5, 10.62), (43.4, 10.45), (44.2, 10.3), (45.0, 10.12), (45.7, 10.5), (46.6, 10.8), (47.6, 11.05), (49.2, 11.3)]
north = [(42.5, 12.5), (49.5, 12.5)]
guban = Polygon(escarp + [(49.5, 11.3)] + north[::-1] + [(42.5, 12.5)])
base_south = [(42.5, 9.0), (46.2, 9.0), (46.0, 9.4)]
basement = Polygon(escarp[:5] + [(45.7, 10.0), (46.3, 9.6), (46.2, 9.0), (42.5, 9.0)])
mesozoic = Polygon([(45.7, 10.5), (46.6, 10.8), (47.6, 11.05), (49.2, 11.3), (49.5, 8.4), (47.0, 8.4), (46.2, 8.9), (46.2, 9.6), (45.7, 10.0)])
haud = Polygon([(42.5, 9.0), (46.2, 9.0), (46.2, 8.9), (47.0, 8.4), (49.5, 8.4), (49.5, 7.5), (42.5, 7.5)])
mesozoic = mesozoic.difference(haud)
def soft(g): return g.buffer(0.12).buffer(-0.24).buffer(0.12)  # round the hand-drawn corners
geo = {
    'guban': soft(guban).intersection(outline),
    'basement': soft(basement.difference(guban)).intersection(outline),
    'mesozoic': soft(mesozoic.difference(guban)).intersection(outline),
    'haud': soft(haud).intersection(outline),
}

places = [
    ('Hargeisa', 44.06, 9.56, 'capital'), ('Berbera', 45.01, 10.44, 'port'), ('Borama', 43.18, 9.94, 'town'),
    ('Burao', 45.53, 9.52, 'town'), ('Erigavo', 47.37, 10.62, 'town'),
    ('Zeila', 43.47, 11.35, 'port'),
]
corridor = [(44.06, 9.56), (44.7, 9.85), (45.2, 9.95), (45.01, 10.44)]

def js(o): return json.dumps(o, ensure_ascii=False, indent=2)
regions = {k: {'d': path(v), 'cx': round(rep(v)[0], 1), 'cy': round(rep(v)[1], 1)} for k, v in parts.items()}
print('// Generated by scripts/build-map-data.py. Do not edit by hand.')
print('// Outline: Natural Earth (public domain). Regions: geoBoundaries (CC BY 4.0), approximated. Geology: generalised.')
print(f'export const MAP_VIEWBOX = {{ w: {W:.0f}, h: {H:.0f} }};')
print('export const MAP_OUTLINE = ' + js(path(outline)) + ';')
print('export const MAP_REGIONS: Record<string, { d: string; cx: number; cy: number }> = ' + js(regions) + ';')
print('export const MAP_GEOLOGY: Record<string, string> = ' + js({k: path(v) for k, v in geo.items()}) + ';')
print('export const MAP_PLACES = ' + js([{'name': n, 'x': round(P(x, y)[0], 1), 'y': round(P(x, y)[1], 1), 'kind': k} for n, x, y, k in places]) + ' as const;')
print('export const MAP_CORRIDOR = ' + js('M' + 'L'.join(f'{P(x,y)[0]:.1f} {P(x,y)[1]:.1f}' for x, y in corridor)) + ';')
