"""Builds src/data/mineralsMrds.ts from data-raw/mrds.tsv (USGS MRDS records mirrored at mineralresourcemap.com).
Assigns each record to a region by point-in-polygon against src/data/mapData.ts. Usage: python3 scripts/build-minerals.py"""
import csv, json, re
from shapely.geometry import Point, Polygon
from shapely.ops import unary_union
src = open('src/data/mapData.ts').read()
regs = json.loads(re.search(r'MAP_REGIONS[^=]*=\s*(\{.*?\n\});', src, re.S).group(1))
ids = {'Awdal': 'awdal', 'Maroodi Jeex': 'maroodiJeex', 'Sahil': 'sahil', 'Togdheer': 'togdheer', 'Sanaag': 'sanaag', 'Sool': 'sool'}
def poly(d):
    return unary_union([Polygon([tuple(map(float, q.replace('Z', '').split())) for q in s.split('L')]).buffer(0) for s in d.split('M')[1:]])
P = {ids[k]: poly(v['d']) for k, v in regs.items()}
def proj(lon, lat): return ((lon - 42.647) * 0.9854 * 150 + 18, (11.4987 - lat) * 150 + 18)
RULES = [(r'beryl', 'beryl', None), (r'columbite', 'niobium', 'columbite'), (r'niobium', 'niobium', None), (r'pyrochlore', 'niobium', 'pyrochlore'),
 (r'tantal', 'tantalum', None), (r'uranium', 'uranium', None), (r'titanium|rutile', 'titanium', 'rutile'), (r'manganese|rhodonite', 'manganese', 'rhodonite'),
 (r'kyanite', 'kyanite', None), (r'graphite', 'graphite', None), (r'quartz|silica', 'quartz', None), (r'talc', 'talc', None), (r'vermiculite', 'vermiculite', None),
 (r'asbestos', 'asbestos', None), (r'barite', 'barite', None), (r'fluorite', 'fluorite', None), (r'\blead\b|galena', 'lead', 'galena'), (r'copper|chalcopyrite', 'copper', None),
 (r'\biron\b|hematite|magnetite', 'iron', None), (r'garnet', 'garnet', None), (r'mica|muscovite', 'mica', None), (r'spinel', 'spinel', None), (r'\btin\b|cassiterite', 'tin', 'cassiterite'),
 (r'tungsten', 'tungsten', None), (r'molybden', 'molybdenum', None), (r'strontium', 'strontium', None), (r'bromine', 'bromine', None), (r'phosphate|guano', 'guano', None),
 (r'silver', 'silver', None), (r'fuller', 'clay', None), (r'crushed', 'stone', None), (r'oil shale', 'oilshale', None)]
HOSTS = [('migmatite', 'migmatite'), ('schist', 'schist'), ('granite', 'granite'), ('gneiss', 'gneiss'), ('gabbro', 'gabbro'), ('pegmatite', 'pegmatite'), ('sandstone', 'sandstone'),
 ('limestone', 'limestone'), ('hornfels', 'hornfels'), ('mudstone', 'mudstone'), ('slate', 'slate'), ('shale', 'shale'), ('marble', 'marble'), ('ultramafic', 'ultramafic'), ('mafic', 'mafic'), ('gravel', 'gravel')]
out = []
for r in csv.DictReader(open('data-raw/mrds.tsv'), delimiter='\t'):
    lat, lon = float(r['lat']), float(r['lon'])
    if lat < 8.5: continue  # southern Somalia
    mins, forms = [], {}
    c = r['commodities'].lower()
    for pat, m, f in RULES:
        if re.search(pat, c):
            if m not in mins: mins.append(m)
            if f and re.search(f, c) or (f and m == 'niobium' and 'pyro' in c): forms[m] = f
    if 'ilmenite' in c: forms['titanium'] = 'ilmenite'
    host = next((h for k, h in HOSTS if k in r['host'].lower()), None)
    x, y = proj(lon, lat); pt = Point(x, y)
    reg = next((k for k, g in P.items() if g.contains(pt)), None)
    if reg is None:
        k, g = min(P.items(), key=lambda kv: kv[1].distance(pt))
        if g.distance(pt) < 40: reg = k
    if reg == 'togdheer' and lat >= 9.95 and lon < 45.5: reg = 'sahil'  # Berbera-Sheikh area: Sheikh belongs to Sahil, the generalised polygon cut is rougher
    name = re.sub(r'\s*\((.*?)\)', '', r['name'])
    name = re.sub(r'\s+(Occurr?e?n?c?e|Occurr5nce|Prospect|Mine|Hot Springs?)$', '', name).strip()
    typ = 'spring' if 'Spring' in r['name'] else 'mine' if r['name'].endswith('Mine') else 'prospect' if 'Prospect' in r['name'] else 'occurrence'
    outside = lon > 48.99
    out.append(dict(id=r['mrds'].lower(), name=name, type=typ, region=None if outside else reg, lon=lon, lat=lat, minerals=mins, host=host, outside=outside or reg is None, ref=r['ref'], dep=r['dep_id']))
body = json.dumps(out, indent=1, ensure_ascii=False)
open('src/data/mineralsMrds.ts', 'w').write("// Generated by scripts/build-minerals.py from USGS MRDS records (via mineralresourcemap.com). Do not edit by hand.\n// Coordinates were transcribed by USGS from 1950s-60s Protectorate survey maps and are rounded to about 2 km.\nimport type { MrdsRow } from './minerals';\nexport const MRDS: MrdsRow[] = " + body + ";\n")
print(len(out), 'rows;', sum(1 for o in out if o['outside']), 'outside;', {k: sum(1 for o in out if o['region'] == k) for k in P})
print([ (o['name'],o['lon'],o['lat']) for o in out if o['outside']])
print([(o['name'], o['minerals']) for o in out if not o['minerals']])
